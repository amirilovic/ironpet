#!/usr/bin/env python3
"""Regenerates Sources/IronPet/Chat/ACP/AgentCatalogData.swift from the ACP registry's agent.json files.

Usage: scripts/gen_agent_catalog.py [path to a registry checkout]
Without an argument it clones https://github.com/agentclientprotocol/registry into a temporary folder.

An entry is { id, name, command, args, viaHelper }. `command` is the executable the user installed; ironpet looks it
up on the login-shell PATH. Agents the registry lists only as npx packages have no executable name in agent.json,
so NPX_COMMANDS names it. Agents in OUT_OF_SCOPE or without a known command are left out.
"""
import glob, json, os, subprocess, sys, tempfile

# Agents that run through a bundled adapter: adapter name, the CLI the adapter drives, and the env var that points to it.
HELPERS = {
    "claude-acp": ("claude", "claude", "CLAUDE_CODE_EXECUTABLE", "Claude Code"),
    "codex-acp": ("codex", "codex", "CODEX_PATH", "Codex"),
    "pi-acp": ("pi", "pi", "PI_ACP_PI_COMMAND", "Pi"),
}
# npx-only registry entries: the executable name the package installs.
NPX_COMMANDS = {
    "gemini": "gemini",
    "github-copilot-cli": "copilot",
    "cline": "cline",
    "auggie": "auggie",
    "qwen-code": "qwen",
    "factory-droid": "droid",
    "codebuddy-code": "codebuddy",
    "kimi-code": "kimi-code",
    "grok-build": "grok",
    "qoder": "qodercli",
    "dirac": "dirac",
    "bob": "bob",
    "nova": "nova",
}
# Binary entries whose registry command is a platform-specific file name; the installed command differs.
COMMAND_OVERRIDES = {"poolside": "pool"}
OUT_OF_SCOPE = {"amp-acp", "antigravity-acp", "deepagents", "glm-acp-agent", "fast-agent", "minion-code", "agoragentic-acp",
                "github-copilot", "opencode-v2", "sigit", "corust-agent", "harn", "vtcode", "cortex-code", "poolside"}
# Names that read better than the registry's.
NAMES = {"opencode": "OpenCode", "cursor": "Cursor", "gemini": "Gemini CLI", "github-copilot-cli": "GitHub Copilot",
         "factory-droid": "Factory Droid", "qwen-code": "Qwen Code", "kiro": "Kiro", "goose": "Goose", "kilo": "Kilo"}


def swift(s):
    return json.dumps(s)


def main():
    root = sys.argv[1] if len(sys.argv) > 1 else None
    tmp = None
    if not root:
        tmp = tempfile.mkdtemp()
        subprocess.run(["git", "clone", "-q", "--depth", "1", "https://github.com/agentclientprotocol/registry", tmp], check=True)
        root = tmp
    commit = subprocess.run(["git", "-C", root, "rev-parse", "--short", "HEAD"], capture_output=True, text=True).stdout.strip()
    rows = []
    for path in sorted(glob.glob(os.path.join(root, "*", "agent.json"))):
        agent = json.load(open(path))
        aid = agent["id"]
        if aid in OUT_OF_SCOPE:
            continue
        dist = agent["distribution"]
        if aid in HELPERS:
            adapter, cli, env, name = HELPERS[aid]
            rows.append((adapter, name, cli, [], (adapter, env)))
            continue
        binary = dist.get("binary", {}).get("darwin-aarch64")
        npx = dist.get("npx")
        if binary:
            command = COMMAND_OVERRIDES.get(aid, os.path.basename(binary["cmd"]))
            args = binary.get("args", [])
        elif npx and aid in NPX_COMMANDS:
            command = NPX_COMMANDS[aid]
            args = npx.get("args", [])
        else:
            continue
        rows.append((aid, NAMES.get(aid, agent["name"]), command, args, None))
    out = ["// Generated by scripts/gen_agent_catalog.py from https://github.com/agentclientprotocol/registry"
           f" ({commit or 'snapshot'}). Do not edit by hand.", "", "extension AgentCatalog {", "    static let snapshot: [ACPAgent] = ["]
    for aid, name, command, args, helper in rows:
        helper_text = "nil" if not helper else f"ACPAgent.Helper(adapter: {swift(helper[0])}, pathVariable: {swift(helper[1])})"
        arg_text = "[" + ", ".join(swift(a) for a in args) + "]"
        out.append(f"        ACPAgent(id: {swift(aid)}, name: {swift(name)}, command: {swift(command)}, args: {arg_text}, helper: {helper_text}),")
    out += ["    ]", "}", ""]
    target = os.path.join(os.path.dirname(__file__), "..", "Sources", "IronPet", "Chat", "ACP", "AgentCatalogData.swift")
    os.makedirs(os.path.dirname(target), exist_ok=True)
    open(target, "w").write("\n".join(out))
    print(f"wrote {len(rows)} agents to {os.path.normpath(target)}")


main()
