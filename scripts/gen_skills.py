#!/usr/bin/env python3
"""Compiles skills/<name>/SKILL.md into Sources/IronPet/Skills/BundledSkillsData.swift.

Run it after adding or editing a skill. A test fails when the generated file is out of date.
A skill is a folder under skills/ with a SKILL.md whose frontmatter has `name` and `description`.
"""
import pathlib
import re
import sys

root = pathlib.Path(__file__).resolve().parent.parent
out = root / "Sources/IronPet/Skills/BundledSkillsData.swift"

entries = []
for skill in sorted((root / "skills").glob("*/SKILL.md")):
    text = skill.read_text()
    folder = skill.parent.name
    match = re.match(r"---\nname: ([^\n]+)\ndescription: ", text)
    if not match or match.group(1) != folder:
        sys.exit(f"{skill}: the frontmatter must start with `name: {folder}` and then `description: `")
    if '"""' in text or '"""#' in text:
        sys.exit(f'{skill}: contains """, which the generated Swift string cannot hold')
    entries.append((folder, text))

lines = [
    "// Generated by scripts/gen_skills.py from skills/*/SKILL.md. Do not edit by hand.",
    "",
    "enum BundledSkillsData {",
    "    static let all: [(name: String, content: String)] = [",
]
for name, text in entries:
    body = text[:-1] if text.endswith("\n") else text
    lines.append(f'        ("{name}", #"""')
    lines.append(body)
    lines.append('"""# + "\\n"),')
lines += ["    ]", "}", ""]
out.write_text("\n".join(lines))
print(f"wrote {out.relative_to(root)} with {len(entries)} skill(s)")
